    private void verificarGanador() {
        // Extraer el texto de las 9 casillas y pasarlo a mayúsculas
        String[] tablero = new String[9];
        for (int i = 0; i < 9; i++) {
            tablero[i] = casillas.get(i).getText().toUpperCase();
        }

        // Combinaciones ganadoras (índices del 0 al 8 correspondientes al ArrayList)
        int[][] combinaciones = {
            {0, 1, 2}, {3, 4, 5}, {6, 7, 8}, // Horizontales
            {0, 3, 6}, {1, 4, 7}, {2, 5, 8}, // Verticales
            {0, 4, 8}, {2, 4, 6}             // Diagonales
        };

        boolean hayGanador = false;

        // Verificar si alguien ganó
        for (int[] combo : combinaciones) {
            String p1 = tablero[combo[0]];
            String p2 = tablero[combo[1]];
            String p3 = tablero[combo[2]];

            if (!p1.isEmpty() && p1.equals(p2) && p1.equals(p3)) {
                textArea1.setText("¡El ganador es " + p1 + "!");
                hayGanador = true;
                
                // Desactivar casillas para que no sigan escribiendo
                for (JTextField casilla : casillas) {
                    casilla.setEnabled(false);
                }
                return; // Termina la función si ya hay ganador
            }
        }

        // Si no hay ganador, verificar si el tablero está lleno (Empate)
        boolean tableroLleno = true;
        for (String valor : tablero) {
            if (valor.isEmpty()) {
                tableroLleno = false;
                break;
            }
        }

        if (tableroLleno && !hayGanador) {
            textArea1.setText("¡Es un empate!");
        }
    }

